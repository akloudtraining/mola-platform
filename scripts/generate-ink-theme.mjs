// Generates app/mola-ink.css, the "Graphite" colour style, from the generated dark theme.
// Same rules, re-scoped to :root[data-palette="ink"] (loaded after mola-dark.css so it wins on equal
// specificity), with forest greens turned into cool graphite greys and gold/green brand accents into mint.
// Status reds and ambers keep their meaning. Run: node scripts/generate-ink-theme.mjs (the dark generator runs it too).
import {readFileSync,writeFileSync} from 'node:fs';
const root=new URL('../app/',import.meta.url);
const COLOR=/#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)/g;
function toRgb(t){if(t[0]==='#'){let h=t.slice(1);if(h.length<=4)h=[...h].map(c=>c+c).join('');const n=parseInt(h.slice(0,6),16);return {r:n>>16&255,g:n>>8&255,b:n&255,a:h.length===8?parseInt(h.slice(6),16)/255:1};}
 const p=t.slice(t.indexOf('(')+1,-1).split(/[\s,/]+/).filter(Boolean).map(v=>v.endsWith('%')?parseFloat(v)*2.55:parseFloat(v));return {r:p[0],g:p[1],b:p[2],a:p.length>3?(p[3]<=1?p[3]:p[3]/255):1};}
function toHsl({r,g,b}){r/=255;g/=255;b/=255;const max=Math.max(r,g,b),min=Math.min(r,g,b),l=(max+min)/2;let h=0,s=0;if(max!==min){const d=max-min;s=l>.5?d/(2-max-min):d/(max+min);h=max===r?(g-b)/d+(g<b?6:0):max===g?(b-r)/d+2:(r-g)/d+4;h/=6;}return {h:h*360,s,l};}
function fromHsl({h,s,l}){h/=360;const f=n=>{const k=(n+h*12)%12,a=s*Math.min(l,1-l);return Math.round(255*(l-a*Math.max(-1,Math.min(k-3,9-k,1))));};return {r:f(0),g:f(8),b:f(4)};}
function out({r,g,b},a){const hex='#'+[r,g,b].map(v=>Math.max(0,Math.min(255,v)).toString(16).padStart(2,'0')).join('');return a>=.999?hex:hex+Math.round(Math.max(0,Math.min(1,a))*255).toString(16).padStart(2,'0');}
const MINT=148,GRAPHITE=210;
function ink(token){
 const rgb=toRgb(token),{h,s,l}=toHsl(rgb),a=rgb.a;
 if(s<.06)return token;                                             // already neutral
 if((h<22||h>335)&&s>.35)return token;                              // status reds
 const gold=h>=28&&h<70,green=h>=70&&h<180;
 if((gold||green)&&s>.33&&l>.22){                                    // brand accents → mint
  const ml=l>.6?Math.min(.82,l):l>.4?Math.max(.6,l):Math.max(.3,l);
  return out(fromHsl({h:MINT,s:l>.4?.66:.5,l:ml}),a);
 }
 if(gold&&s>.33)return out(fromHsl({h:MINT,s:.32,l}),a);             // deep gold icon wells → deep mint
 return out(fromHsl({h:GRAPHITE,s:Math.min(s,.09),l}),a);            // forest surfaces, tinted text → graphite
}
const dark=readFileSync(new URL('mola-dark.css',root),'utf8').replace(/^\/\*[\s\S]*?\*\/\n/,'');
const body=dark.replace(/\[data-theme="dark"\]/g,'[data-palette="ink"]').replace(COLOR,ink);
const tuned=readFileSync(new URL('mola-ink-tuning.css',root),'utf8');
writeFileSync(new URL('mola-ink.css',root),`/* GENERATED by scripts/generate-ink-theme.mjs from mola-dark.css. Do not edit by hand;\n   adjust app/mola-ink-tuning.css (appended last) or the mapping in the script, then re-run. */\n${body}\n/* hand tuning */\n${tuned}`);
console.log('mola-ink.css written');
